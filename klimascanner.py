from .utils.license_utils.license_utils import calc_data_available

class Klimascanner:
    
    def __init__(self, iface):
        self.iface = iface
        self.layer, self.canvas = iface.activeLayer(), iface.mapCanvas()
        # Laden des Processing Tools
        self.provider = None
        self.initProcessing()
        
        # read calc data path from QGIS-Config
        self.plugin_dir = os.path.dirname(__file__)

        # initialize locale
        locale = (QSettings().value('locale/userLocale') or 'de')[0:2]
        locale_path = os.path.join(
            self.plugin_dir,
            'i18n',
            'Klimascanner_{}.qm'.format(locale))
        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)
            QCoreApplication.installTranslator(self.translator)

        # declare instance attributes
        self.actions = []
        self.menu = self.tr(u'&KLIMASCANNER')
        self.toolbar = self.iface.addToolBar(u'KLIMASCANNER')
        self.toolbar.setObjectName(u'KLIMASCANNER')

        self.pluginIsActive = False

    def tr(self, message):
        return QCoreApplication.translate('Klimascanner', message)

    def initProcessing(self):
        """Init Processing provider for QGIS >= 3.8."""
        registry = QgsApplication.processingRegistry()
        # verhindert doppelte Registrierung unter derselben id (siehe unload())
        existing = registry.providerById('klimascanner')
        if existing is not None:
            registry.removeProvider(existing)
        self.provider = KlimascannerCalculationProcessingProvider()
        registry.addProvider(self.provider)

    def add_action(
            self,
            icon_path,
            isCheckable,
            text,
            callback,
            enabled_flag=True,
            add_to_menu=True,
            add_to_toolbar=True,
            status_tip=None,
            whats_this=None,
            parent=None):

        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)
        action.setCheckable(isCheckable)

        if status_tip is not None:
            action.setStatusTip(status_tip)

        if whats_this is not None:
            action.setWhatsThis(whats_this)

        if add_to_toolbar:
            self.toolbar.addAction(action)

        if add_to_menu:
            self.iface.addPluginToMenu(
                self.menu,
                action)

        self.actions.append(action)

        return action

    # initialize the user interface
    def initGui(self):
        # define Picker Button / Action
        icon_path = ':/plugins/klimascanner/icon_picker.png'
        self.pickerAction = self.add_action(
            icon_path,
            True,
            text=self.tr(u'KLIMASCANNER-Picker'),
            callback=self.runPicker,
            parent=self.iface.mainWindow())
        
        # create instance of picker and declare its pickerAction
        self.picker = Klimascanner_Picker(
            self.canvas, self.layer, self.iface, self.pickerAction)

        # define calculation Button / Action
        icon_path = ':/plugins/klimascanner/icon_calculate.png'
        self.calculateAction = self.add_action(
            icon_path,
            False,
            text=self.tr(u'KLIMASCANNER-Calculation'),
            callback=self.runCalculate,
            parent=self.iface.mainWindow())

        # define About Button / Action
        icon_path = ':/plugins/klimascanner/icon_about.png'
        self.aboutAction = self.add_action(
            icon_path,
            False,
            text=self.tr(u'KLIMASCANNER-About'),
            callback=self.runAbout,
            parent=self.iface.mainWindow())
        self.about = Klimascanner_About(self.iface, self.update_action_states)

        self.update_action_states()

    def update_action_states(self):
        """Grays out Picker/Calculation until valid calc data is present."""
        available = calc_data_available()
        self.pickerAction.setEnabled(available)
        self.calculateAction.setEnabled(available)

    def onClosePlugin(self):
        """Cleanup necessary items here when plugin is closed"""
        # disconnects
        self.pluginIsActive = False

    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""
        try:
            QgsApplication.processingRegistry().removeProvider(self.provider)
        except RuntimeError:
            pass  # Provider-Objekt war C++-seitig schon geloescht

        if hasattr(self, 'picker'):
            self.picker.unload()

        for action in self.actions:
            self.iface.removePluginMenu(
                self.tr(u'&KLIMASCANNER'),
                action)
            self.iface.removeToolBarIcon(action)
        # remove the toolbar
        del self.toolbar

    # run picker component
    def runPicker(self):
        self.picker.run()
       

    # run about component
    def runAbout(self):
        self.about.run()

    # run calculation component
    def runCalculate(self):
        if not check_license_is_valid("calculation"):
            return

        # Andocken beim Zeichnen ist seit QGIS 4.2 kaputt (QGIS-Bug #66817), daher
        # feste Groesse statt des zu klein angedockten Standardzustands erzwingen.
        try:
            from processing.gui.algorithm_widget import AlgorithmWidget
            alg = QgsApplication.processingRegistry().createAlgorithmById('klimascanner:calculate')
            widget = alg.createCustomParametersWidget(self.iface.mainWindow())
            if not widget:
                widget = AlgorithmWidget(
                    alg, parent=self.iface.mainWindow(),
                    initialState=Qgis.DockableWidgetInitialState.ForceDialog)
            widget.setParameters({})
            widget.setMinimumSize(700, 600)
            widget.exec()
            widget.close()
        except Exception:
            execAlgorithmDialog('klimascanner:calculate', {})