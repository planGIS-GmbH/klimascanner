    def styleLayer(self, pathToLayer, layerName, calcDataStylePath, defaultStylePath, context, feedback):
        # load and name the layers
        if ("VECTOR" in layerName):
            layer = QgsVectorLayer(pathToLayer, layerName, "ogr")
        else:
            layer = QgsRasterLayer(pathToLayer, layerName)

        groupName = layerName.split("_")[1]
        layerType = layerName.split("_")[2]

        if ("wd" in groupName and ("PLAN" in layerType or "IST" in layerType)):
            parts = layerName.split("_")
            direction = "PLAN" if "PLAN" in layerType else "IST"
            res_suffix = ""
            if len(parts) > 3 and parts[3].endswith('m') and parts[3][:-1].isdigit():
                res_suffix = "_" + parts[3]
            styleFile = f"{groupName}_{direction}{res_suffix}.qml"
            if res_suffix and not os.path.exists(calcDataStylePath + styleFile) and not os.path.exists(defaultStylePath + styleFile):
                styleFile = f"{groupName}_{direction}.qml"
