    # generate DIFF layer (raster data)
    def genDiffLayerRaster(self, valueId, outputFolder, feedback):
        try:
            # determine output folder for value
            folderName = self.outPutParametersReadableDict[valueId] 
            outputValueFolder = outputFolder + '/' + folderName
            
            layerPlanName = self.planningLayerPrefix + valueId + self.datetimeString
            layerIsName = self.isLayerPrefix + valueId + self.datetimeString
            layerNameOutput = self.diffLayerPrefix + valueId + self.datetimeString

            pathToPlanTif = outputValueFolder + "/" + layerPlanName + ".tif"
            pathToIsTif = outputValueFolder + "/" + layerIsName + ".tif"
            pathToTifOutput = outputValueFolder + "/" + layerNameOutput + ".tif"

            feedback.pushInfo(f"Berechne Differenz aus {pathToPlanTif} und {pathToIsTif}...")

            # open both layers
            with rasterio.open(pathToPlanTif) as plan, rasterio.open(pathToIsTif) as ist:
                plan_data = plan.read(1)
                ist_data = ist.read(1)
                profile = plan.profile.copy()

                # determine NoData
                nodata = plan.nodata if plan.nodata is not None else -999
                mask = (plan_data == nodata) | (ist_data == nodata)

                # calculate diff and round to 3 decimal places
                diff = np.round(plan_data - ist_data, 3)
                diff[mask] = nodata

            # actualize output profile
            # driver must be forced to GTiff: GDAL may have opened the source file
            # with its read-only LIBERTIFF driver, which profile.copy() would carry
            # over and which has no writer
            profile.update(driver='GTiff', dtype=rasterio.float32, compress='DEFLATE', nodata=nodata)

            # write diff data
            with _force_rasterio_proj_data(), rasterio.open(pathToTifOutput, "w", **profile) as dst:
                dst.write(diff.astype(rasterio.float32), 1)

            # normalization and postprocessing
            self.normalizeBuildings(pathToTifOutput)
            self.setNoDataValue(pathToTifOutput)

            # save return value
            self.returnValue["LAYER_" + valueId + "_DIFF"] = pathToTifOutput

        except Exception as e:
            # if error, break processing and throw error message
            raise QgsProcessingException(
                f"ERROR: {layerNameOutput}-Layer konnte nicht erstellt werden!\n"
                f"Pfad: {pathToTifOutput}\n"
                f"Fehler: {str(e)}\n\n"
                f"Stacktrace:" + traceback.format_exc())

