@contextlib.contextmanager
def _force_rasterio_proj_data():
    """
    QGIS/OSGeo4W and the pip-installed rasterio wheel each ship their own PROJ
    library and proj.db. QGIS processing algorithms (e.g. the gdal:* provider)
    set PROJ_LIB/PROJ_DATA to OSGeo4W's (older) proj.db as a side effect, which
    then makes rasterio's bundled (newer) PROJ fail with a
    "DATABASE.LAYOUT.VERSION" mismatch once it needs to resolve an EPSG code.
    Force rasterio's own proj_data dir just for the risky call, then restore
    whatever was set before so QGIS/GDAL keep seeing their own paths.
    """
    proj_data_dir = os.path.join(os.path.dirname(rasterio.__file__), 'proj_data')
    keys = ('PROJ_LIB', 'PROJ_DATA')
    previous = {key: os.environ.get(key) for key in keys}
    if os.path.isdir(proj_data_dir):
        for key in keys:
            os.environ[key] = proj_data_dir
    try:
        yield
    finally:
        for key, value in previous.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value



