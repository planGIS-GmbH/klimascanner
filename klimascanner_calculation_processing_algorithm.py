    # postprocessing: sorting, grouping, layer styling
    def postProcessAlgorithm(self, context, feedback):
        # sort layer by type (pet14, t14, ...)                  
        sortedReturnValuesTemp = collections.OrderedDict(
            sorted(self.returnValue.items(), reverse=True))
        sortedReturnValues = {}
        for param in self.outputParametersSortingOrder:
            for key, value in sortedReturnValuesTemp.items():
                if param in key:
                    sortedReturnValues[key] = value

        # wind direction vector layers are keyed "LAYER_wd_<PLAN|IST>_<n>m_VECTOR";
        # reorder each PLAN/IST block by resolution (descending) so the
        # insert-at-top grouping logic below renders them ascending (5m on top,
        # 200m on the bottom)
        def windResolution(key):
            parts = key.split("_")
            if len(parts) >= 4 and parts[3].endswith('m') and parts[3][:-1].isdigit():
                return int(parts[3][:-1])
            return 0

        allKeys = list(sortedReturnValues.keys())
        for layerType in ("PLAN", "IST"):
            blockKeys = [k for k in allKeys
                         if k.split("_")[1] == "wd" and k.split("_")[2] == layerType]
            if not blockKeys:
                continue
            orderedBlock = sorted(blockKeys, key=windResolution, reverse=True)
            if orderedBlock == blockKeys:
                continue
            firstIndex = allKeys.index(blockKeys[0])
            remainingKeys = [k for k in allKeys if k not in blockKeys]
            allKeys = remainingKeys[:firstIndex] + orderedBlock + remainingKeys[firstIndex:]
        sortedReturnValues = {k: sortedReturnValues[k] for k in allKeys}

        # create group
        root = QgsProject.instance().layerTreeRoot()
        resultGroup = root.addGroup("Klimascanner_Calculation" + self.datetimeString)
        resultGroup.setExpanded(True)
        tempGroupName = ""
        anzGroups = 0
        tempWdSubGroups = {}
        deferredWdVw = None

        # iterate over result layer and sort layer in groups
        for key, value in sortedReturnValues.items():
            groupName = key.split("_")[1]
            layerType = key.split("_")[2]

            # only set first group visible
            if not groupName == tempGroupName:
                tempGroup = resultGroup.addGroup(
                    self.outPutParametersReadableDict[groupName])
                if (anzGroups == 0):
                    tempGroup.setExpanded(True)
                else:
                    tempGroup.setExpanded(False)
                    tempGroup.setItemVisibilityCheckedRecursive(False)
                tempGroupName = groupName
                tempWdSubGroups = {}
                anzGroups = anzGroups + 1

            calcDataStylePath = os.path.join(self.calcDataInputPath, 'styles', '')
            defaultStylePath = os.path.join(self.plugin_dir, 'styles', '')
            layer = self.styleLayer(value, key, calcDataStylePath, defaultStylePath, context, feedback)

            # name layers and add to the layer tree of QGIS
            if (groupName == "wd" or layerType == "VW"):
                parts = key.split("_")
                if len(parts) >= 4 and parts[3].endswith('m') and parts[3][:-1].isdigit():
                    layer.setName(groupName + "_" + layerType + "_" + parts[3])
                else:
                    layer.setName(groupName + "_" + layerType)
            else:
                stats = layer.dataProvider().bandStatistics(1, QgsRasterBandStats.Stats.All)
                rounded = str(self.round_half_up(stats.mean, 2))
                layer.setName(groupName + "_" + layerType + " (Avg: " + rounded + ")")

            QgsProject.instance().addMapLayer(layer)

            layerId = root.findLayer(layer.id())
            if not "DIFF" in layerType:
                layerId.setItemVisibilityChecked(False)

            # wind direction layers go into PLAN/IST subgroups; VW is processed
            # before those subgroups exist (reverse-alpha order), so it is
            # deferred and appended at the end once they've been created
            if groupName == "wd" and layerType in ("PLAN", "IST"):
                if layerType not in tempWdSubGroups:
                    tempWdSubGroups[layerType] = tempGroup.addGroup(layerType)
                self.moveLayerToGroup(layerId, tempWdSubGroups[layerType])
            elif groupName == "wd" and layerType == "VW":
                deferredWdVw = (layerId, tempGroup)
            else:
                self.moveLayerToGroup(layerId, tempGroup)

        if deferredWdVw is not None:
            self.moveLayerToGroupEnd(*deferredWdVw)

        # set group to first place in layer tree
        self.setGroupToTheTop(resultGroup)
        return {}

    def round_half_up(self, n, decimals=0):
        multiplier = 10 ** decimals
        return math.floor(n*multiplier + 0.5) / multiplier
    
    def addVectordataToRaster_in_order(self, vector, attributeNutz, attributeStrh, rasterPathNutz,rasterPathStrh, order_values):
        
        # copy data from clip extent to IST filename
        try: 
            rasterPathIst = rasterPathNutz.replace("_ce.tif", "_ist.tif")
            shutil.copy(rasterPathNutz, rasterPathIst)
        except Exception as e:
            raise RuntimeError(f"Kopie der Ist-Datei fehlgeschlagen: {e}")

        # Nutz
        dst_ds_nutz = gdal.Open(rasterPathNutz, gdal.GA_Update)
        if dst_ds_nutz is None:
            raise RuntimeError(f"Raster kann nicht geöffnet werden: {rasterPathNutz}")
        
        # Strh
        dst_ds_strh = gdal.Open(rasterPathStrh, gdal.GA_Update)
        if dst_ds_strh is None:
            raise RuntimeError(f"Raster kann nicht geöffnet werden: {rasterPathStrh}")
        
        # extract vector data source (Path + optional layername) from QGIS-URI
        uri = vector.dataProvider().dataSourceUri()
        ds_path = uri.split('|')[0]

        # validate if attribute filed is existing
        # Nutz
        if vector.fields().indexFromName(attributeNutz) < 0:
            dst_ds_nutz = None
            raise ValueError(f"Attributfeld '{attributeNutz}' nicht gefunden.")
        
        # Strh
        if vector.fields().indexFromName(attributeStrh) < 0:
            dst_ds_strh = None
            raise ValueError(f"Attributfeld '{attributeStrh}' nicht gefunden.")

        # detect types for correct WHERE-quoting
        attr_idx = vector.fields().indexFromName(attributeNutz)
        attr_type = vector.fields()[attr_idx].type()  # QVariant.Type

        # function for building WHERE-clause for a single value
        def build_where(val):
            # set quotes only for strings
            if attr_type in (QVariant.String, QVariant.Date, QVariant.DateTime, QVariant.Time):
                # single escapes for quote
                sval = str(val).replace("'", "''")
                return f"\"{attributeNutz}\" = '{sval}'"
            else:
                return f"\"{attributeNutz}\" = {val}"

        # multiple rasterization in desired order
        for val in order_values:
            where_clause = build_where(val)
            optsNutz = gdal.RasterizeOptions(
                attribute=attributeNutz, 
                where=where_clause
            )
            optsStrh = gdal.RasterizeOptions(
                attribute=attributeStrh, 
                where=where_clause
            )
            # rasterization
            # srcDS -> path of source (Dataset), layer selection with option
            gdal.Rasterize(dst_ds_nutz, ds_path, options=optsNutz)
            gdal.Rasterize(dst_ds_strh, ds_path, options=optsStrh)

        # flush cache
        dst_ds_nutz.FlushCache()
        dst_ds_nutz = None
        dst_ds_strh.FlushCache()
        dst_ds_strh = None     
        
    # move group to top in layer tree
    def setGroupToTheTop(self, group):
        clone = group.clone()
        parent = group.parent()
        parent.insertChildNode(0, clone)
        parent.removeChildNode(group)

    # add layer to given group
    def moveLayerToGroup(self, layerId, group):
        layerClone = layerId.clone()
        layerParent = layerId.parent()
        layerClone.setExpanded(False)
        group.insertChildNode(0, layerClone)
        layerParent.removeChildNode(layerId)

    # same as moveLayerToGroup, but appends at the end instead of the top
    def moveLayerToGroupEnd(self, layerId, group):
        layerClone = layerId.clone()
        layerParent = layerId.parent()
        layerClone.setExpanded(False)
        group.insertChildNode(len(group.children()), layerClone)
        layerParent.removeChildNode(layerId)

