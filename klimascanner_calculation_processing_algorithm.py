    # delete features in vector data layer with value -999.0
    def deleteNoDataInVectorLayer(self, attributeName, layer):
        layer.startEditing()
        features = layer.getFeatures()
        for feat in features:
            if (feat[attributeName] == -999.0 or feat[attributeName] == 999.0):
                layer.deleteFeature(feat.id())
        layer.commitChanges()
        return layer

    # rename attribute values
    def renameAttributes(self, layer, attributesDict):
        layer.startEditing()
        layer.dataProvider().renameAttributes(attributesDict)
        layer.commitChanges()
        layer.updateFields()

    # mask outlier as no data values
    def normalizeBuildings(self, pathToTiff):
        with rio.open(pathToTiff) as src:
            array = src.read()
            profile = src.profile
            array[np.where(array < -900)] = -999
            array[np.where(array > 900)] = -999

        # driver must be forced to GTiff: GDAL may have opened the source file
        # with its read-only LIBERTIFF driver, which profile would carry over
        # and which has no writer
        profile.update(driver='GTiff')
        with _force_rasterio_proj_data(), rio.open(pathToTiff, 'w', **profile) as dst:
            dst.write(array)

    # set no data value (QGIS specific = -999)
    def setNoDataValue(self, pathToTiff):
        # 1: opening the file to edit it
        ds = gdal.Open(pathToTiff, 1)
        rb = ds.GetRasterBand(1) # assuming your raster has 1 band
        rb.SetNoDataValue(-999)
        rb = None
        ds = None

    # convert xyz points to raster
    def compute_raster_meta_from_xyz(self, xyz_array: np.ndarray):
        x = xyz_array[:, 0]
        y = xyz_array[:, 1]
        z = xyz_array[:, 2]

        x = np.round(x).astype(int)
        y = np.round(y).astype(int)
        unique_x = np.unique(x)
        unique_y = np.unique(y)
        cols = len(unique_x)
        rows = len(unique_y)

        # sort for correct gdal compatible raster (rows: top → bottom)
        sorted_indices = np.lexsort((x, -y))
        z_sorted = z[sorted_indices]
        raster = z_sorted.reshape((rows, cols))

        # calculate pixel size
        pixel_width = unique_x[1] - unique_x[0]
        pixel_height = unique_y[1] - unique_y[0]

        # transform (upper left is the origin)
        transform = rasterio.transform.from_origin(
            west=min(unique_x) - pixel_width / 2,
            north=max(unique_y) + pixel_height / 2,
            xsize=pixel_width,
            ysize=pixel_height
        )

        return raster, transform, (rows, cols), z.dtype
    
    # function ton only round the first to columns
    def round_first_two_columns(self,data_dict):
        for key, arr in data_dict.items():
            arr[:, :2] = np.round(arr[:, :2], decimals=2) # rounds only the first two columns
        return data_dict

    # generate csv from raster tif
    def generateCSV(self,pathToTif,pathToCSV):
        if pathToCSV.endswith('.csv'):
            pathToCSV_temp = pathToCSV.replace('.csv','.csv_temp')
            gdal.Translate(pathToCSV_temp,pathToTif, format='XYZ',creationOptions = ['DECIMAL_PRECISION=1'])
        elif pathToCSV.endswith('.xyz'):
            pathToCSV_temp = pathToCSV.replace('.xyz','.xyz_temp')
            gdal.Translate(pathToCSV_temp,pathToTif, format='XYZ',creationOptions = ['DECIMAL_PRECISION=2'])
        
        # postprocessing
        with open(pathToCSV_temp, 'r') as infile, open(pathToCSV, 'w') as outfile:
             # set header
            outfile.write('x,y,z\n')   
            for line in infile:
                # replace spaces with comma
                outfile.write(','.join(line.strip().split()) + '\n')
                
    # get epsg from extent, if epsg is written inside extent
    def get_extent_epsg(self, extent_param_name,parameters):
        import re
        epsg = None

        # try to extract EPSG from raw value of parameter (String with "[EPSG:xxxx]")
        raw = parameters.get(extent_param_name)
        if isinstance(raw, str):
            m = re.search(r'\[EPSG:(\d+)\]', raw)
            if m:
                epsg = int(m.group(1))
                epsg = "EPSG:"+str(epsg)

        return epsg
