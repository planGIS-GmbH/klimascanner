    def _create_wind_fgb(self, u_2d, v_2d, x_2d, y_2d, agg_m, output_path):
        """Average u/v over agg_nxagg_n blocks, compute WD/WS, save as FlatGeobuf."""
        from shapely.geometry import Point
        agg_n = int(agg_m // self.pixelSize)
        rows, cols = u_2d.shape

        if agg_n > 1:
            rows_trim = (rows // agg_n) * agg_n
            cols_trim = (cols // agg_n) * agg_n
            n_r = rows_trim // agg_n
            n_c = cols_trim // agg_n

            def block_mean(arr):
                return np.nanmean(
                    arr[:rows_trim, :cols_trim].reshape(n_r, agg_n, n_c, agg_n),
                    axis=(1, 3)
                )

            u_2d = block_mean(u_2d)
            v_2d = block_mean(v_2d)
            x_2d = block_mean(x_2d.astype(np.float64))
            y_2d = block_mean(y_2d.astype(np.float64))

        u_flat = u_2d.ravel()
        v_flat = v_2d.ravel()
        x_flat = x_2d.ravel()
        y_flat = y_2d.ravel()

        valid = ~(np.isnan(u_flat) | np.isnan(v_flat))
        u_flat, v_flat = u_flat[valid], v_flat[valid]
        x_flat, y_flat = x_flat[valid], y_flat[valid]

        ws = np.round(np.sqrt(u_flat**2 + v_flat**2).astype(np.float32), 2)
        wd = np.round((np.degrees(np.arctan2(u_flat, v_flat)) % 360).astype(np.float32), 2)

        gdf = gpd.GeoDataFrame(
            {'WD': wd, 'WS': ws},
            geometry=[Point(x, y) for x, y in zip(x_flat, y_flat)],
            crs=self.EPSG
        )
        gdf.to_file(output_path, driver='FlatGeobuf')

