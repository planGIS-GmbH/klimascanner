_restart_triggered = False


def _restart_qgis(iface):
    """Startet QGIS mit demselben Projekt neu.

    Der neue Prozess wird erst beim aboutToQuit-Signal gestartet, also erst
    nachdem eine eventuelle "Projekt speichern?"-Abfrage beantwortet wurde
    (und gar nicht, falls der Nutzer den Exit dort abbricht). sys.executable
    wird hier bewusst nicht verwendet - je nach QGIS-Installationsart (OSGeo4W
    vs. Standalone-Installer) zeigt das nicht zuveraessig auf qgis-bin.exe,
    sondern teils auf ein bloßes python.exe. QgsApplication.applicationFilePath()
    liefert stattdessen immer den Pfad der tatsaechlich laufenden Anwendung.

    Gegen Mehrfachaufrufe (z. B. falls initGui() mehrfach laeuft) abgesichert,
    da sonst mehrere Listener an aboutToQuit haengen und beim Beenden jeder
    fuer sich einen eigenen neuen QGIS-Prozess starten wuerde.
    """
    global _restart_triggered
    if _restart_triggered:
        return
    _restart_triggered = True

    mark_restart_attempted(_numpy_spec)

    app = QgsApplication.instance()

    def _launch_new_instance():
        args = [QgsApplication.applicationFilePath()]
        project_path = QgsProject.instance().fileName()
        if project_path:
            args.append(project_path)
        subprocess.Popen(args)

    app.aboutToQuit.connect(_launch_new_instance)
    iface.actionExit().trigger()


class _RestartRequiredPlugin:
    """Platzhalter, falls numpy aktualisiert werden muesste, aber im laufenden
    QGIS-Prozess schon geladen ist (siehe check_dependencies.check) - ein Update
    waere hier nicht sicher moeglich, deshalb stattdessen Neustart anbieten."""

    def __init__(self, iface):
        self.iface = iface

    def initGui(self):
        box = QMessageBox(self.iface.mainWindow())
        box.setIcon(QMessageBox.Icon.Warning)
        box.setWindowTitle("QGIS-Neustart erforderlich")
        box.setText(
            "KLIMASCANNER benötigt eine Aktualisierung einer Python-Abhängigkeit (numpy).\n\n"
            "numpy war in dieser QGIS-Sitzung aber bereits geladen, daher kann das nicht "
            "sicher zur Laufzeit abgeschlossen werden. Bitte starten Sie QGIS jetzt neu, "
            "damit die Aktualisierung automatisch und sauber durchgeführt wird."
        )
        restart_button = box.addButton("Jetzt neu starten", QMessageBox.ButtonRole.AcceptRole)
        box.addButton("Später", QMessageBox.ButtonRole.RejectRole)
        box.exec()
        if box.clickedButton() == restart_button:
            _restart_qgis(self.iface)

    def unload(self):
        pass


